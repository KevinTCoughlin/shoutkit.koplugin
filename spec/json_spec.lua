local Json = require("lib.json")

describe("Json.decode", function()
    it("decodes scalars, objects and arrays", function()
        local value = Json.decode('{"a":1,"b":[1,2,3],"d":"x\\ty","e":true,"f":-2.5e3}')
        assert_.equal(1, value.a)
        assert_.len(3, value.b)
        assert_.equal("x\ty", value.d)
        assert_.equal(true, value.e)
        assert_.equal(-2500, value.f)
    end)

    it("omits null object values so absence is testable", function()
        local value = Json.decode('{"geo_lat":null,"name":"x"}')
        assert_.nil_(value.geo_lat)
        assert_.equal("x", value.name)
    end)

    it("keeps array nulls as a sentinel so indices do not shift", function()
        local value = Json.decode("[1,null,3]")
        assert_.len(3, value)
        assert_.equal(Json.null, value[2])
        assert_.equal(3, value[3])
    end)

    it("joins surrogate pairs, which station names really do contain", function()
        local value = Json.decode('["Caf\\u00e9 \\ud83c\\udfb5"]')
        assert_.equal("Caf\195\169 \240\159\142\181", value[1])
    end)

    it("returns an error rather than raising on malformed input", function()
        assert_.nil_((Json.decode('{"bad":')))
        assert_.truthy(select(2, Json.decode('{"bad":')))
        assert_.truthy(select(2, Json.decode("{} trailing")))
        assert_.truthy(select(2, Json.decode("")))
    end)
end)
